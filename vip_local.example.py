"""VIP 개인 주소 목록의 **형식 예시**입니다. 실제 주소는 들어 있지 않습니다.

사용법
------
이 파일을 vip_local.py 로 복사하고 실제 주소를 채우세요.

    cp vip_local.example.py vip_local.py

vip_local.py 는 .gitignore 에 등록되어 있어 커밋되지 않습니다.
파일이 없어도 파이프라인은 정상 동작합니다 — VIP_P1(P1) 규칙만 발화하지
않습니다. config._load_vip_addresses 참고.

왜 분리했나
-----------
개인 주소는 제3자 데이터이고 이 저장소는 공개될 수 있습니다. 기관 도메인
(config.VIP_P0_DOMAINS)은 공개 정보이므로 로직의 일부로 남겨두지만, 개인
주소는 README §7 하드룰이 코드·문서·커밋에 넣는 것을 금지합니다.

"조심해서 넣지 않기"는 언젠가 실패합니다. 목록이 사는 파일을 .gitignore
안으로 옮겨, 실수해도 커밋되지 않는 구조로 막습니다.

형식
----
- 소문자·대문자 구분 없이 적어도 됩니다 (읽는 쪽에서 소문자로 정규화합니다).
- **주소 정확 일치**입니다. 도메인 전체를 넣을 수는 없습니다 —
  그렇게 하면 같은 회사의 자동발송·마케팅까지 전부 P1이 됩니다.
- 여기 있는 주소는 P1 + needs_reply=true 로 분류되어 다이제스트의
  "답장 대기" 섹션에 올라갑니다.
"""

